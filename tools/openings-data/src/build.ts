const hash8 = (s: string) => createHash('sha256').update(s).digest('hex').slice(0, 8);

function attachPopularity(openings: MergedOpening[]): number {
	const pop = computePopularity(loadPopCache('lichess'), loadPopCache('masters'));
	let n = 0;
	for (const { entry } of openings) {
		const p = pop.get(entry.epd);
		if (p) {
			entry.popularity = p;
			n++;
		}
	}
	return n;
}

async function main() {
	await downloadSources(process.argv.includes('--refresh-sources'));
	const { lichess, eco } = loadSources();
	const { openings, stats } = mergeOpenings(lichess, eco);
	console.log('merge:', stats);

	const withPopularity = attachPopularity(openings);

	// Notes: keyed by EPD, chunked by the smallest ECO letter among openings through that position.
	const notes = buildNotes(collectPrefixes(openings), loadNotesCache());
	const ecoThrough = new Map<string, { eco: string }[]>();
	for (const { entry, epds } of openings) {
		for (const e of new Set(epds.slice(1))) {
			const list = ecoThrough.get(e) ?? [];
			list.push({ eco: entry.eco });
			ecoThrough.set(e, list);
		}
	}
	const chunks: Record<string, NotesFile> = {};
	for (const letter of ['A', 'B', 'C', 'D', 'E']) chunks[letter] = { version: DATA_VERSION, notes: {} };
	for (const [epd, note] of notes) {
		const letter = notesChunkOf(ecoThrough.get(epd) ?? []) ?? 'A';
		chunks[letter]!.notes[epd] = note;
	}
	for (const { entry } of openings) if (notes.has(entry.epd)) entry.hasNotes = true;

	const graph = buildGraph(openings, DATA_VERSION);
	const openingsFile: OpeningsFile = { version: DATA_VERSION, openings: openings.map((o) => o.entry) };

	mkdirSync(OUT_DIR, { recursive: true });
	const written: string[] = [];
	const sizes: string[] = [];
	const emit = (base: string, data: unknown): string => {
		const json = JSON.stringify(data);
		const name = `${base}.${hash8(json)}.json`;
		writeFileSync(resolve(OUT_DIR, name), json);
		written.push(name);
		sizes.push(`${name}: ${(json.length / 1024).toFixed(0)} KB raw, ${(gzipSync(json).length / 1024).toFixed(0)} KB gzip`);
		return name;
	};
	const v = `v${DATA_VERSION}`;
	const manifest: OpeningsManifest = {
		version: DATA_VERSION,
		generatedAt: new Date().toISOString(),
		counts: { openings: openingsFile.openings.length, positions: graph.epd.length, notes: notes.size, withPopularity },
		files: {
			openings: emit(`openings.${v}`, openingsFile),
			graph: emit(`graph.${v}`, graph),
			notes: Object.fromEntries(Object.entries(chunks).map(([l, c]) => [l, emit(`notes.${v}.${l}`, c)])),
		},
		attribution: ATTRIBUTION,
	};
	writeFileSync(resolve(OUT_DIR, 'manifest.json'), JSON.stringify(manifest, null, '\t') + '\n');
	writeFileSync(resolve(OUT_DIR, 'ATTRIBUTION.md'), ATTRIBUTION_MD);

	// Remove stale hashed outputs.
	const keep = new Set(written);
	for (const f of readdirSync(OUT_DIR)) {
		if (/^(openings|graph|notes)\.v\d+\..*\.json$/.test(f) && !keep.has(f)) {
			rmSync(resolve(OUT_DIR, f));
			console.log(`removed stale ${f}`);
		}
	}
	console.log('counts:', manifest.counts);
	for (const s of sizes) console.log('  ' + s);
}

main().catch((e) => {
	console.error(e);
	process.exit(1);
});
